'use strict';
/**
 * loom/templates/system-scaffold.js — "build another system on the fly."
 * comp_id: nexus.loom.templates.system-scaffold
 * UUID: nexus-loom-scaffold-v1-0000-2026-0702-jamesbrooks-001
 * Phase: 145 (this session)
 *
 * The generalized version of what Phase 131 did specifically for LOOM.
 * One list of operations goes in; five real, working projections come
 * out, generated in the exact order you specified:
 *
 *   1. component/seam/hook/wire  — registered into LOOM (via LoomDriver),
 *                                  not just written as a file
 *   2. CLI                        — cli/index.js, first, per your order
 *   3. API                        — api/index.js, second
 *   4. file maps + configs        — registry-components.js, mirrors the
 *                                  real pattern already used by
 *                                  architect/idearium/ollama's own files
 *   5. interaction contract       — interaction-contract.json, shape
 *                                  copied from idearium's real, live one
 *                                  (id/version/namespace/port/transport/
 *                                  resources), not invented
 *
 *   UI is explicitly NOT generated. scaffoldSystem() has no UI-producing
 *   code path at all — not "disabled," not "TODO," genuinely absent —
 *   because generating even a stub UI here would violate the one rule
 *   you set for this whole build order.
 *
 * Why one operations list drives four outputs instead of four hand-
 * written files: this is Architect's own stated principle applied
 * generatively — "the spec IS the system, code is a projection of the
 * spec." Here the operations list is that spec-equivalent. Change an
 * operation once, regenerate, all four projections stay consistent —
 * the alternative (hand-maintaining CLI commands, API routes, and a
 * contract file separately) is exactly how they drift apart.
 */
const fs = require('fs');
const path = require('path');
const { LoomDriver } = require('../schema/index');

/**
 * Operation shape (the one thing you define per system):
 *   { id, verb, method, apiPath, params: [], description }
 * `verb` -> CLI command (e.g. "list", "create"). `method`+`apiPath` -> API route.
 */
function _validateOperations(operations) {
  if (!Array.isArray(operations) || operations.length === 0) {
    throw new Error('[scaffold] operations must be a non-empty array');
  }
  for (const op of operations) {
    for (const key of ['id', 'verb', 'method', 'apiPath']) {
      if (!op[key]) throw new Error(`[scaffold] operation missing required key "${key}": ${JSON.stringify(op)}`);
    }
  }
}

// ── Projection 2: CLI (first) ───────────────────────────────────────────────
function _renderCli(systemName, operations) {
  const cases = operations.map(op => `    case '${op.verb}': {
      const result = await dispatch('${op.id}', args);
      console.log(JSON.stringify(result, null, 2));
      break;
    }`).join('\n');

  return `'use strict';
/**
 * ${systemName}/cli/index.js — generated by loom/templates/system-scaffold.js
 * Do not hand-edit the verb list below; regenerate from the operations
 * list instead, or CLI/API drift apart the way phase 64/hook-registry did.
 *
 * Usage: node ${systemName}/cli/index.js <verb> [--key value ...]
 */
const { dispatch } = require('../api/index');

function _parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith('--')) {
      const key = argv[i].slice(2);
      const val = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true;
      out[key] = val;
    }
  }
  return out;
}

async function main() {
  const [verb, ...rest] = process.argv.slice(2);
  const args = _parseArgs(rest);
  switch (verb) {
${cases}
    default:
      console.error(\`Unknown verb: \${verb}\`);
      console.error('Available: ${operations.map(o => o.verb).join(', ')}');
      process.exit(1);
  }
}

if (require.main === module) main();
module.exports = { main };
`;
}

// ── Projection 3: API (second) — same dispatch() the CLI calls ─────────────
function _renderApi(systemName, operations, port) {
  const dispatchCases = operations.map(op => `    case '${op.id}': return { ok: true, op: '${op.id}', args, note: 'stub handler — replace with real logic' };`).join('\n');
  // §BUG FOUND BY DOGFOODING (clearglass-accounts, this session): naive
  // startsWith() route matching in declaration order means a shorter
  // path like /api/accounts always shadows a longer, more specific one
  // like /api/accounts/usage — the longer route is dead code, always
  // caught by the shorter check first. Fix: sort longest-path-first so
  // the most specific match always wins. This was a real bug in
  // generated output, not a hypothetical — caught the moment a real
  // system with overlapping paths was actually built and run.
  const sorted = [...operations].sort((a, b) => b.apiPath.length - a.apiPath.length);
  const routes = sorted.map(op => `  if (req.method === '${op.method}' && req.url.startsWith('${op.apiPath}')) {
    const result = await dispatch('${op.id}', args);
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify(result));
    return;
  }`).join('\n');

  return `'use strict';
/**
 * ${systemName}/api/index.js — generated by loom/templates/system-scaffold.js
 * dispatch() is the single source both CLI and API call — one place to
 * implement real behavior, not two surfaces that quietly diverge.
 * Routes below are ordered longest-path-first — see comment in the
 * generator (system-scaffold.js) for why that ordering is load-bearing.
 */
const http = require('http');
const { URL } = require('url');

const PORT = parseInt(process.env.${systemName.toUpperCase().replace(/-/g, '_')}_PORT || '${port}', 10);

async function dispatch(opId, args) {
  switch (opId) {
${dispatchCases}
    default: return { ok: false, error: \`unknown operation: \${opId}\` };
  }
}

function createServer() {
  return http.createServer(async (req, res) => {
    const u = new URL(req.url, \`http://\${req.headers.host || 'localhost'}\`);
    const args = Object.fromEntries(u.searchParams);
${routes}
    res.writeHead(404, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ ok: false, error: 'no matching route' }));
  });
}

if (require.main === module) {
  createServer().listen(PORT, () => console.log(\`${systemName} API on :\${PORT}\`));
}

module.exports = { dispatch, createServer, PORT };
`;
}

// ── Projection 4: registry-components.js — real pattern, not invented ──────
function _renderRegistryComponents(systemName, operations) {
  const entries = operations.map(op =>
    `  _c('${op.id}', '${op.method}', '${op.apiPath}', ${JSON.stringify(op.description || op.id)}${op.params ? `, { params: ${JSON.stringify(op.params)} }` : ''}),`
  ).join('\n');

  return `'use strict';
/**
 * ${systemName}/registry-components.js — generated by loom/templates/system-scaffold.js
 * comp_id: nexus.${systemName}.registry
 * Same shape as architect/registry-components.js and idearium/registry-components.js.
 */
const V = '0.1.0'; const NS = '${systemName}';
function _c(id, method, path, desc, opts = {}) {
  return {
    id: \`\${NS}.\${id}\`, namespace: NS, name: id, version: V,
    route: { method, path }, description: desc,
    params: opts.params || [], tags: [NS, ...(opts.tags || [])],
    permissions: opts.permissions || ['system'],
  };
}
module.exports = [
${entries}
];
`;
}

// ── Projection 5: interaction-contract.json — copied shape from idearium ───
function _renderInteractionContract(systemName, operations, port) {
  const resources = {};
  for (const op of operations) {
    resources[op.id] = {
      endpoints: {
        [op.verb]: { method: op.method, path: op.apiPath, ...(op.params ? { params: op.params } : {}) },
      },
    };
  }
  return {
    id: `${systemName}-v1`,
    version: '0.1.0',
    namespace: systemName,
    port,
    transport: {
      http: `http://127.0.0.1:${port}`,
      guardian: 'http://127.0.0.1:7820',
    },
    resources,
  };
}

/**
 * scaffoldSystem(name, { port, purpose, operations, outDir, dataDir })
 * -> { written: [...paths], registered: {component, hooks} }
 *
 * Writes the four projections to disk under outDir/<name>/, and
 * registers the system as a real LOOM component with one hook per
 * operation, wired nowhere yet (wiring is Phase 3's job, per the
 * Lattice L3 note — a fresh system starts with hooks, not wires,
 * exactly like your real "164 hooks replayed, 0 live wires" today).
 */
function scaffoldSystem(name, { port, purpose = '', operations, outDir, dataDir = null } = {}) {
  if (!name || !/^[a-z][a-z0-9-]*$/.test(name)) {
    throw new Error('[scaffold] name must be lowercase, start with a letter, e.g. "my-system"');
  }
  if (!port) throw new Error('[scaffold] port is required');
  _validateOperations(operations);
  if (!outDir) throw new Error('[scaffold] outDir is required');

  const sysDir = path.join(outDir, name);
  const dirs = ['cli', 'api', 'docs'];
  for (const d of dirs) fs.mkdirSync(path.join(sysDir, d), { recursive: true });

  const written = [];
  function _write(rel, content) {
    const full = path.join(sysDir, rel);
    fs.writeFileSync(full, content);
    written.push(full);
  }

  // Projection 1 — spec (matches warp.spec / ARCHITECT-SPEC's real meta header shape)
  const specTs = new Date().toISOString();
  _write('docs/' + name + '.spec.md', `# ${name}
## Generated by loom/templates/system-scaffold.js
**Version:** 0.1.0
**Generated:** ${specTs}
**Purpose:** ${purpose || '(not specified — fill in before this system does anything real)'}
**Port:** ${port}

## Operations
${operations.map(o => `- **${o.id}** (\`${o.verb}\`) — ${o.method} ${o.apiPath}${o.description ? ' — ' + o.description : ''}`).join('\n')}

## Status
Scaffolded, not implemented. CLI and API below are real, runnable, and
return stub responses — replace dispatch() in api/index.js with real
logic. This file grows as the system builds, per the timestamp above —
append, do not overwrite, on every real change (§6.3, spec is living
and tracked).
`);

  // Projection 2 — CLI (first)
  _write('cli/index.js', _renderCli(name, operations));

  // Projection 3 — API (second)
  _write('api/index.js', _renderApi(name, operations, port));

  // Projection 4 — file maps + configs
  _write('registry-components.js', _renderRegistryComponents(name, operations));

  // Projection 5 — interaction contract (last of the five, still before UI)
  _write('interaction-contract.json', JSON.stringify(_renderInteractionContract(name, operations, port), null, 2));

  // Register into LOOM's own component/seam/hook/wire registry — dogfooded,
  // same as Warp and LOOM's own agent-suite were.
  const driver = new LoomDriver({ dataDir });
  const compId = `nexus.${name}`;
  const compResult = driver.declare('component', {
    id: compId, namespace: name, name, version: '0.1.0',
    uuid: `nexus-${name}-v1-0000-2026-0702-jamesbrooks-scaffold`,
  });

  const hookResults = [];
  if (compResult.ok) {
    for (const op of operations) {
      const r = driver.declare('hook', {
        id: `${compId}.${op.id}`, component_id: compId, name: op.id,
        type: 'api', direction: 'out',
        uuid: `nexus-${name}-hook-${op.id}-v1-0000-2026-0702-jamesbrooks-scaffold`,
      });
      hookResults.push(r);
    }
  }

  return { written, registered: { component: compResult, hooks: hookResults } };
}

module.exports = { scaffoldSystem };
